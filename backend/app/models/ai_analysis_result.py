"""
models/ai_analysis_result.py

AI Security Analysis Output Contract — P2G

AIAnalysisResult is the canonical structured output produced by the
SecurityAnalysisService after analyzing VulnerabilityFinding records
through an LLM provider.

Key design rules:
    - NEVER modifies underlying vulnerability facts (CVE, CVSS, EPSS, risk_score, fixed_version)
    - ALWAYS preserves finding_id → analysis traceability
    - Separates FACT from INFERENCE from RECOMMENDATION
    - Gracefully degrades on AI failure (ai_status field)
    - Source of truth remains VulnerabilityFinding, not this output

AI Responsibility:
    EXPLAIN | PRIORITIZE | CONTEXTUALIZE | RECOMMEND based on supplied evidence

AI Must NOT:
    Invent CVEs, package versions, fixed versions, CVSS/EPSS scores, or
    vulnerability existence claims.
"""

from typing import Optional
from pydantic import BaseModel, Field

# AI output contract version — increment only on BREAKING output schema changes
AI_OUTPUT_CONTRACT_VERSION = "1.0"

# ── AI Status semantics ───────────────────────────────────────────────────────
AI_STATUS_NOT_REQUESTED = "not_requested"
AI_STATUS_COMPLETED = "completed"
AI_STATUS_COMPLETED_WITH_WARNINGS = "completed_with_warnings"
AI_STATUS_UNAVAILABLE = "unavailable"
AI_STATUS_FAILED = "failed"


class AIFindingAnalysis(BaseModel):
    """
    Structured AI analysis for a single VulnerabilityFinding.

    Every field in this class is AI-generated explanation/reasoning.
    This class MUST NOT modify any factual fields from VulnerabilityFinding.

    Traceability:
        finding_id links this analysis back to the canonical VulnerabilityFinding.
        Dashboard and reporting modules use finding_id to join AI explanations
        to the raw facts without ambiguity.
    """

    # ── Traceability — REQUIRED ────────────────────────────────────────────────
    finding_id: str = Field(
        ...,
        description=(
            "Links this analysis back to the VulnerabilityFinding.finding_id. "
            "This field is NEVER generated by the AI — it is always set from the "
            "corresponding VulnerabilityFinding before the AI prompt is constructed."
        ),
    )

    # ── AI-generated explanation fields ───────────────────────────────────────
    priority: int = Field(
        default=1,
        ge=1,
        description=(
            "Priority rank of this finding within the scan (1 = highest priority). "
            "Derived from the deterministic prioritization layer, not AI-assigned."
        ),
    )
    explanation: Optional[str] = Field(
        default=None,
        description=(
            "AI explanation of what this vulnerability means in the context of the "
            "affected package and dependency. Based entirely on supplied evidence."
        ),
    )
    impact: Optional[str] = Field(
        default=None,
        description=(
            "AI reasoning about potential security consequences, based on CVE/CVSS "
            "evidence. Explicitly marked as INFERENCE where not directly evidenced."
        ),
    )
    exploitability: Optional[str] = Field(
        default=None,
        description=(
            "AI commentary on exploitability evidence — based on EPSS, CVSS vector, "
            "and available exploit references only. Never fabricated."
        ),
    )
    remediation: Optional[str] = Field(
        default=None,
        description=(
            "AI remediation reasoning. Always references the fixed_version from the "
            "VulnerabilityFinding when available. Never invents a version."
        ),
    )
    dependency_context_note: Optional[str] = Field(
        default=None,
        description=(
            "AI note on whether this is a direct or transitive dependency and "
            "what that means for remediation effort. Based on dependency context data."
        ),
    )
    attack_surface: Optional[str] = Field(
        default=None,
        description="AI assessment of the exposed attack surface, based on CVSS vector analysis.",
    )
    confidence: Optional[str] = Field(
        default=None,
        description=(
            "Evidence confidence level: HIGH (CVE + CVSS + EPSS all present), "
            "MEDIUM (partial scoring data), LOW (severity label only). "
            "NOT model confidence — this reflects the evidence quality."
        ),
    )


class AIAnalysisResult(BaseModel):
    """
    Top-level AI Security Analysis Result — P2G output contract.

    This is the canonical structured output for:
        - Dashboard / Visualization module
        - Report Generator
        - Future DevSecOps integrations

    Downstream consumers MUST use finding_id to join analysis results
    back to VulnerabilityFinding records. Never parse prose directly.

    Contract version: 1.0
    """

    contract_version: str = Field(
        default=AI_OUTPUT_CONTRACT_VERSION,
        description="Output schema contract version.",
    )

    # ── Scan Identity ─────────────────────────────────────────────────────────
    scan_id: Optional[str] = Field(
        default=None,
        description="Propagated from the original scan — unchanged throughout the pipeline.",
    )

    # ── AI Status ─────────────────────────────────────────────────────────────
    ai_status: str = Field(
        default=AI_STATUS_COMPLETED,
        description=(
            "not_requested | completed | completed_with_warnings | unavailable | failed\n"
            "IMPORTANT: An 'unavailable' or 'failed' AI status does NOT mean the "
            "vulnerability scan failed. Check the underlying VulnerabilityFinding records."
        ),
    )
    ai_error: Optional[str] = Field(
        default=None,
        description="Error message if ai_status is 'unavailable' or 'failed'.",
    )
    llm_provider: Optional[str] = Field(
        default=None,
        description="Name of the LLM provider used (e.g. 'MockLLMProvider', 'OpenAI', 'Gemini').",
    )

    # ── Overall Analysis ──────────────────────────────────────────────────────
    executive_summary: Optional[str] = Field(
        default=None,
        description=(
            "AI-generated executive summary of the overall security posture. "
            "Synthesizes all findings into a concise risk overview."
        ),
    )
    overall_risk: Optional[str] = Field(
        default=None,
        description=(
            "AI overall risk assessment: CRITICAL / HIGH / MEDIUM / LOW / UNKNOWN. "
            "Derived from the highest-risk findings analyzed."
        ),
    )
    total_findings_analyzed: int = Field(
        default=0,
        description="Number of VulnerabilityFinding records analyzed in this session.",
    )

    # ── Finding-Level Analysis ────────────────────────────────────────────────
    finding_analyses: list[AIFindingAnalysis] = Field(
        default_factory=list,
        description=(
            "Per-finding AI analysis records. Each must contain a finding_id. "
            "Use finding_id to join back to VulnerabilityFinding for raw facts."
        ),
    )
